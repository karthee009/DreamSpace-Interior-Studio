CREATE DATABASE IF NOT EXISTS dreamspace_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE dreamspace_db;

CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('CUSTOMER','DESIGNER','STAFF','ADMIN') NOT NULL DEFAULT 'CUSTOMER',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS enquiries (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL,
 phone VARCHAR(40) NULL,
 message TEXT NOT NULL,
 status ENUM('NEW','CONTACTED','CONVERTED','CLOSED') NOT NULL DEFAULT 'NEW',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS projects (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(180) NOT NULL,
 description TEXT NULL,
 status ENUM('ENQUIRY','PLANNING','DESIGNING','REVIEW','APPROVED','ORDERED','COMPLETED') NOT NULL DEFAULT 'PLANNING',
 budget DECIMAL(12,2) NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_projects_user FOREIGN KEY(user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS rooms (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 project_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(120) NOT NULL,
 room_type VARCHAR(60) NOT NULL DEFAULT 'Living room',
 length_m DECIMAL(7,2) NOT NULL,
 width_m DECIMAL(7,2) NOT NULL,
 height_m DECIMAL(7,2) NOT NULL DEFAULT 2.8,
 notes TEXT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_rooms_project FOREIGN KEY(project_id) REFERENCES projects(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS room_photos (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 room_id BIGINT UNSIGNED NOT NULL,
 stored_name VARCHAR(255) NOT NULL,
 original_name VARCHAR(255) NOT NULL,
 mime_type VARCHAR(100) NOT NULL,
 size_bytes BIGINT UNSIGNED NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_photos_room FOREIGN KEY(room_id) REFERENCES rooms(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS products (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(180) NOT NULL,
 category VARCHAR(100) NOT NULL,
 product_type ENUM('READY_MADE','CUSTOM_MADE','MATERIAL') NOT NULL DEFAULT 'READY_MADE',
 description TEXT NULL,
 length_m DECIMAL(7,2) NOT NULL DEFAULT 1,
 width_m DECIMAL(7,2) NOT NULL DEFAULT 1,
 height_m DECIMAL(7,2) NOT NULL DEFAULT 1,
 price DECIMAL(12,2) NOT NULL DEFAULT 0,
 image_url VARCHAR(255) NULL,
 stock_qty INT NOT NULL DEFAULT 0,
 low_stock_threshold INT NOT NULL DEFAULT 2,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (price >= 0),
 CHECK (stock_qty >= 0)
);

CREATE TABLE IF NOT EXISTS designs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 project_id BIGINT UNSIGNED NOT NULL,
 room_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(180) NOT NULL DEFAULT 'Design version 1',
 scene_json JSON NOT NULL,
 version_no INT NOT NULL DEFAULT 1,
 approved BOOLEAN NOT NULL DEFAULT FALSE,
 created_by BIGINT UNSIGNED NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_design_project FOREIGN KEY(project_id) REFERENCES projects(id) ON DELETE CASCADE,
 CONSTRAINT fk_design_room FOREIGN KEY(room_id) REFERENCES rooms(id) ON DELETE CASCADE,
 CONSTRAINT fk_design_user FOREIGN KEY(created_by) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS quotations (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 project_id BIGINT UNSIGNED NOT NULL,
 created_by BIGINT UNSIGNED NOT NULL,
 quote_number VARCHAR(40) NOT NULL UNIQUE,
 status ENUM('DRAFT','SENT','ACCEPTED','REJECTED','EXPIRED','REVISED') NOT NULL DEFAULT 'DRAFT',
 items_json JSON NOT NULL,
 subtotal DECIMAL(12,2) NOT NULL,
 tax_rate DECIMAL(5,2) NOT NULL DEFAULT 0,
 tax_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
 total DECIMAL(12,2) NOT NULL,
 valid_until DATE NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_quotes_project FOREIGN KEY(project_id) REFERENCES projects(id),
 CONSTRAINT fk_quotes_user FOREIGN KEY(created_by) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 project_id BIGINT UNSIGNED NOT NULL,
 quotation_id BIGINT UNSIGNED NULL,
 status ENUM('PENDING','CONFIRMED','IN_PRODUCTION','READY','DELIVERED','INSTALLED','CANCELLED') NOT NULL DEFAULT 'PENDING',
 notes TEXT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_orders_project FOREIGN KEY(project_id) REFERENCES projects(id),
 CONSTRAINT fk_orders_quote FOREIGN KEY(quotation_id) REFERENCES quotations(id)
);

CREATE TABLE IF NOT EXISTS stock_movements (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 product_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 quantity_delta INT NOT NULL,
 reason VARCHAR(255) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_stock_product FOREIGN KEY(product_id) REFERENCES products(id),
 CONSTRAINT fk_stock_user FOREIGN KEY(user_id) REFERENCES users(id)
);

